/**
 * Local temp disk, not the persistent data root: the preview process lives on
 * one instance, and file watching does not work on the Azure Files share.
 */
const WORKSPACE_ROOT = path.join(os.tmpdir(), 'apex-code-lab');
/** Lockfile-keyed dependency cache, also on local disk so it never fills the shared data root. */
const DEPENDENCY_CACHE_ROOT = path.join(os.tmpdir(), 'apex-code-lab-deps');
const CLONE_TIMEOUT_MS = 10 * 60 * 1000;
const CLONE_IDLE_TIMEOUT_MS = 2 * 60 * 1000;
const MAX_ACTIVE_SESSIONS = 4;
const IDLE_TIMEOUT_MS = 30 * 60 * 1000;
const REAPER_INTERVAL_MS = 60 * 1000;
const PREVIEW_READY_TIMEOUT_MS = 3 * 60 * 1000;
const PREVIEW_KILL_GRACE_MS = 5000;
const MAX_LOG_LINES = 400;
const VITE_WRAPPER_DIR = '.codelab';
const VITE_WRAPPER_FILE = 'vite.codelab.config.mjs';

const VITE_WRAPPER_SOURCE = `// Generated by Apex Code Lab. Wraps the project's Vite config with preview settings.
import { loadConfigFromFile, mergeConfig } from 'vite';

export default async (env) => {
  const loaded = await loadConfigFromFile(env, undefined, process.env.CODE_LAB_APP_DIR);
  return mergeConfig(loaded ? loaded.config : {}, {
    base: process.env.CODE_LAB_BASE,
    cacheDir: process.env.CODE_LAB_CACHE_DIR,
    clearScreen: false,
    server: {
      host: '127.0.0.1',
      port: Number(process.env.CODE_LAB_PORT),
      strictPort: true,
      open: false,
      hmr: false,
      fs: { allow: JSON.parse(process.env.CODE_LAB_FS_ALLOW || '[]') },
    },
  });
};
`;

/**
 * Request headers forwarded to the preview server. Cookies and credentials never
 * are, and accept-encoding is dropped so HTML arrives uncompressed for rewriting.
 */
const FORWARDED_REQUEST_HEADERS = [
  'accept',
  'accept-language',
  'if-modified-since',
  'if-none-match',
  'range',
  'user-agent',
] as const;

const DROPPED_RESPONSE_HEADERS = new Set([
  'connection',
  'keep-alive',
  'transfer-encoding',
  'set-cookie',
  'x-frame-options',
  'content-security-policy',
  'access-control-allow-origin',
  'access-control-allow-credentials',
]);

/**
 * Applied to every preview response. The CSP sandbox keeps the preview in an
 * opaque origin even when opened in its own tab, so it never runs as Apex.
 */
const PREVIEW_RESPONSE_HEADERS: Record<string, string> = {
  'Content-Security-Policy': 'sandbox allow-scripts allow-forms allow-popups allow-modals allow-downloads',
  'Access-Control-Allow-Origin': '*',
  'Cross-Origin-Resource-Policy': 'cross-origin',
  'Referrer-Policy': 'no-referrer',
  'X-Content-Type-Options': 'nosniff',
};

interface CodeLabSessionRecord {
  session: CodeLabSession;
  userId: string;
  token: string;
  provider: SkillProvider;
  workspaceDir: string;
  appDir: string | null;
  previewProcess: ChildProcess | null;
  previewPort: number | null;
  lastActivityMs: number;
  logs: string[];
}

export class CodeLabError extends Error {
  constructor(message: string, readonly status: number) {
    super(message);
    this.name = 'CodeLabError';
  }
}

const sessions = new Map<string, CodeLabSessionRecord>();
let reaperTimer: NodeJS.Timeout | null = null;
let exitHookInstalled = false;

function previewBasePath(record: Pick<CodeLabSessionRecord, 'session' | 'token'>): string {
  return `/api${CODE_LAB_PREVIEW_ROUTE}${record.session.id}/${record.token}/`;
}

function toPublic(record: CodeLabSessionRecord): CodeLabSession {
  return { ...record.session, lastActivityAt: new Date(record.lastActivityMs).toISOString() };
}

function setStatus(record: CodeLabSessionRecord, status: CodeLabSessionStatus, detail: string | null): void {
  if (record.session.status === 'stopped') return;
  record.session.status = status;
  record.session.statusDetail = detail;
  if (detail) appendLog(record, `[code-lab] ${detail}`);
}

function appendLog(record: CodeLabSessionRecord, text: string): void {
  // eslint-disable-next-line no-control-regex
  const clean = text.replace(/\x1b\[[0-9;]*[A-Za-z]/g, '');
  for (const line of clean.split(/\r?\n/)) {
    if (!line.trim()) continue;
    record.logs.push(line);
  }
  if (record.logs.length > MAX_LOG_LINES) {
    record.logs.splice(0, record.logs.length - MAX_LOG_LINES);
  }
}

function isStopped(record: CodeLabSessionRecord): boolean {
  return record.session.status === 'stopped';
}

function touch(record: CodeLabSessionRecord): void {
  record.lastActivityMs = Date.now();
}

function ensureBackgroundTasks(): void {
  if (!reaperTimer) {
    reaperTimer = setInterval(() => {
      const cutoff = Date.now() - IDLE_TIMEOUT_MS;
      for (const record of sessions.values()) {
        if (record.lastActivityMs < cutoff) {
          console.log(`[code-lab] stopping idle session ${record.session.id}`);
          void stopRecord(record);
        }
      }
    }, REAPER_INTERVAL_MS);
    reaperTimer.unref();
  }
  if (!exitHookInstalled) {
    exitHookInstalled = true;
    process.once('exit', () => {
      for (const record of sessions.values()) record.previewProcess?.kill('SIGKILL');
    });
  }
}

async function resolveCheckout(project: string): Promise<{
  provider: SkillProvider;
  repo: string;
  baseBranch: string;
  developmentModel: string | undefined;
}> {
  const skillConfig = await getSkillConfig(project);
  const provider = skillConfig?.skillProvider ?? 'ado';
  const repo = skillConfig?.skillRepo ?? project;
  const baseBranch = skillConfig?.skillBranch
    ?? (provider === 'github'
      ? await githubCatalog.getDefaultBranch(repo)
      : await new AzureDevOpsService(project).getDefaultBranch(repo, project));
  return { provider, repo, baseBranch, developmentModel: skillConfig?.developmentModel ?? undefined };
}

/** Keeps preview scaffolding and the symlinked dependency tree out of diffs and commits. */
function excludeCodeLabFilesFromGit(workspaceDir: string): void {
  const excludePath = path.join(workspaceDir, '.git', 'info', 'exclude');
  fs.mkdirSync(path.dirname(excludePath), { recursive: true });
  const existing = fs.existsSync(excludePath) ? fs.readFileSync(excludePath, 'utf-8') : '';
  const prefix = existing.length > 0 && !existing.endsWith('\n') ? '\n' : '';
  fs.appendFileSync(excludePath, `${prefix}# Apex Code Lab\n${VITE_WRAPPER_DIR}/\nnode_modules\n`, 'utf-8');
}

function readPackageJson(dir: string): PackageJsonLike | null {
  const file = path.join(dir, 'package.json');
  if (!fs.existsSync(file)) return null;
  try {
    return JSON.parse(fs.readFileSync(file, 'utf-8')) as PackageJsonLike;
  } catch {
    return null;
  }
}

function detectPreview(workspaceDir: string): CodeLabPreviewInfo {
  const candidates: PreviewCandidate[] = CODE_LAB_APP_DIR_CANDIDATES
    .map((appDir) => ({ appDir, abs: path.join(workspaceDir, appDir) }))
    .filter(({ abs }) => fs.existsSync(abs))
    .map(({ appDir, abs }) => ({
      appDir,
      packageJson: readPackageJson(abs),
      hasIndexHtml: fs.existsSync(path.join(abs, 'index.html')),
    }));
  return resolvePreviewPlan(candidates);
}

function findFreePort(): Promise<number> {
  return new Promise((resolve, reject) => {
    const server = net.createServer();
    server.unref();
    server.on('error', reject);
    server.listen(0, '127.0.0.1', () => {
      const address = server.address();
      const port = typeof address === 'object' && address ? address.port : 0;
      server.close(() => resolve(port));
    });
  });
}

function probePreview(port: number, urlPath: string): Promise<boolean> {
  return new Promise((resolve) => {
    const probe = http.request(
      { host: '127.0.0.1', port, path: urlPath, method: 'GET', timeout: 5000 },
      (res) => {
        res.resume();
        resolve((res.statusCode ?? 500) < 500);
      },
    );
    probe.on('timeout', () => probe.destroy());
    probe.on('error', () => resolve(false));
    probe.end();
  });
}

function resolveViteEntry(appDirAbs: string, workspaceDir: string): string | null {
  for (const base of [appDirAbs, workspaceDir]) {
    const entry = path.join(base, 'node_modules', 'vite', 'bin', 'vite.js');
    if (fs.existsSync(entry)) return entry;
  }
  return null;
}

function realPathOrNull(target: string): string | null {
  try {
    return fs.realpathSync(target);
  } catch {
    return null;
  }
}

/** Only what Node and npm need; Apex's secrets never reach repository code. */
function previewEnv(extra: Record<string, string>): NodeJS.ProcessEnv {
  const passthrough = ['PATH', 'HOME', 'USERPROFILE', 'TMPDIR', 'TEMP', 'TMP', 'SystemRoot', 'LANG'];
  const env: NodeJS.ProcessEnv = {};
  for (const key of passthrough) {
    if (process.env[key]) env[key] = process.env[key];
  }
  return {
    ...env,
    NODE_ENV: 'development',
    BROWSER: 'none',
    FORCE_COLOR: '0',
    NODE_OPTIONS: '--max-old-space-size=1024',
    ...extra,
  };
}

async function startVitePreview(record: CodeLabSessionRecord, appDirAbs: string): Promise<void> {
  const viteEntry = resolveViteEntry(appDirAbs, record.workspaceDir);
  if (!viteEntry) {
    setStatus(record, 'preview_unavailable', 'Vite is not installed in this repository, so the preview cannot start.');
    return;
  }

  const wrapperDir = path.join(appDirAbs, VITE_WRAPPER_DIR);
  fs.mkdirSync(wrapperDir, { recursive: true });
  const wrapperPath = path.join(wrapperDir, VITE_WRAPPER_FILE);
  fs.writeFileSync(wrapperPath, VITE_WRAPPER_SOURCE, 'utf-8');

  const fsAllow = [
    record.workspaceDir,
    appDirAbs,
    realPathOrNull(path.join(appDirAbs, 'node_modules')),
    realPathOrNull(path.join(record.workspaceDir, 'node_modules')),
  ].filter((entry): entry is string => Boolean(entry));

  const port = await findFreePort();
  const basePath = previewBasePath(record);
  const child = spawn(process.execPath, [viteEntry, '--config', wrapperPath], {
    cwd: appDirAbs,
    env: previewEnv({
      CODE_LAB_APP_DIR: appDirAbs,
      CODE_LAB_BASE: basePath,
      CODE_LAB_CACHE_DIR: path.join(wrapperDir, 'vite-cache'),
      CODE_LAB_PORT: String(port),
      CODE_LAB_FS_ALLOW: JSON.stringify([...new Set(fsAllow)]),
    }),
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  record.previewProcess = child;
  record.previewPort = port;
  child.stdout?.on('data', (chunk: Buffer) => appendLog(record, chunk.toString()));
  child.stderr?.on('data', (chunk: Buffer) => appendLog(record, chunk.toString()));
  child.on('exit', (code, signal) => {
    if (record.previewProcess !== child) return;
    record.previewProcess = null;
    record.session.previewUrl = null;
    setStatus(
      record,
      'preview_unavailable',
      `The preview server stopped (${signal ?? `exit code ${code}`}). Check the Logs tab, then restart the preview.`,
    );
  });

  const deadline = Date.now() + PREVIEW_READY_TIMEOUT_MS;
  while (Date.now() < deadline) {
    if (record.previewProcess !== child || isStopped(record)) return;
    if (await probePreview(port, basePath)) {
      record.session.previewUrl = basePath;
      setStatus(record, 'ready', null);
      return;
    }
    await new Promise((resolve) => setTimeout(resolve, 1000));
  }
  setStatus(record, 'preview_unavailable', 'The preview server did not respond within 3 minutes. Check the Logs tab.');
  stopPreviewProcess(record);
}

async function startPreview(record: CodeLabSessionRecord): Promise<void> {
  const preview = record.session.preview;
  if (!preview || isStopped(record)) return;
  const appDirAbs = path.join(record.workspaceDir, preview.appDir);
  record.appDir = appDirAbs;

  switch (preview.kind) {
    case 'unsupported':
      setStatus(record, 'preview_unavailable', preview.reason ?? 'This app cannot be previewed.');
      return;
    case 'static':
      record.session.previewUrl = previewBasePath(record);
      setStatus(record, 'ready', null);
      return;
    case 'vite':
      setStatus(record, 'starting_preview', `Starting the ${preview.label} preview`);
      await startVitePreview(record, appDirAbs);
      return;
    default: {
      const unreachable: never = preview.kind;
      throw new Error(`Unhandled preview kind: ${String(unreachable)}`);
    }
  }
}

function stopPreviewProcess(record: CodeLabSessionRecord): void {
  const child = record.previewProcess;
  record.previewProcess = null;
  record.previewPort = null;
  record.session.previewUrl = null;
  if (!child || child.exitCode !== null) return;
  child.kill('SIGTERM');
  setTimeout(() => {
    if (child.exitCode === null) child.kill('SIGKILL');
  }, PREVIEW_KILL_GRACE_MS).unref();
}

/**
 * Clones only the base branch tip onto local disk. The shared repo cache needs
 * 10 GiB free on the data root for a cold mirror, and a session never needs history.
 */
async function cloneLatestCommit(
  record: CodeLabSessionRecord,
  checkout: { provider: SkillProvider; repo: string; baseBranch: string },
): Promise<void> {
  const remote = resolveGitRemote(checkout.provider, record.session.project, checkout.repo);
  fs.mkdirSync(WORKSPACE_ROOT, { recursive: true });
  fs.rmSync(record.workspaceDir, { recursive: true, force: true });
  try {
    await git(
      [
        '-c',
        'core.longpaths=true',
        'clone',
        '--depth',
        '1',
        '--single-branch',
        '--no-tags',
        '--branch',
        checkout.baseBranch,
        remote.url,
        record.workspaceDir,
      ],
      {
        cwd: WORKSPACE_ROOT,
        timeout: CLONE_TIMEOUT_MS,
        idleTimeout: CLONE_IDLE_TIMEOUT_MS,
        env: remote.env,
      },
    );
  } catch (err) {
    fs.rmSync(record.workspaceDir, { recursive: true, force: true });
    const raw = err instanceof Error ? err.message : String(err);
    throw new Error(`git clone failed: ${redactSecrets(raw, remote.secret)}`);
  }
}

async function runSetup(record: CodeLabSessionRecord, model: string | undefined): Promise<void> {
  const { session } = record;
  try {
    const checkout = await resolveCheckout(session.project);
    record.provider = checkout.provider;
    session.repo = checkout.repo;
    session.baseBranch = checkout.baseBranch;
    if (isStopped(record)) return;

    setStatus(record, 'preparing', `Checking out ${checkout.repo} at ${checkout.baseBranch}`);
    await cloneLatestCommit(record, checkout);
    await checkoutNewBranch(record.workspaceDir, session.branchName);
    excludeCodeLabFilesFromGit(record.workspaceDir);
    if (isStopped(record)) return;

    setStatus(record, 'preparing', 'Installing dependencies');
    let dependenciesPrepared = false;
    try {
      await bootstrapDevelopmentDependencies(record.workspaceDir, {
        dataRoot: DEPENDENCY_CACHE_ROOT,
        onPhase: (_phase, detail) => appendLog(record, detail),
      });
      dependenciesPrepared = true;
    } catch (err) {
      appendLog(record, `[code-lab] Dependency install failed: ${(err as Error).message}`);
    }
    if (isStopped(record)) return;

    const thread = await createThread(record.userId, {
      project: session.project,
      repo: checkout.repo,
      branch: session.branchName,
      skillBranch: checkout.baseBranch,
      skillProvider: checkout.provider,
      model: model ?? checkout.developmentModel,
      agentModule: 'development',
      mode: 'development',
      codeLab: true,
    }, {
      skipAutoKickoff: true,
      workspaceDirOverride: record.workspaceDir,
      dependenciesPrepared,
    });
    session.chatThreadId = thread.id;
    if (isStopped(record)) return;

    session.preview = detectPreview(record.workspaceDir);
    if (!dependenciesPrepared && session.preview.kind === 'vite') {
      setStatus(record, 'preview_unavailable', 'Dependencies could not be installed, so the preview cannot start. Check the Logs tab.');
      return;
    }
    await startPreview(record);
  } catch (err) {
    const message = (err as Error).message;
    console.error(`[code-lab] setup failed for session ${session.id}:`, message);
    setStatus(record, 'failed', `Setup failed: ${message}`);
  }
}

async function stopRecord(record: CodeLabSessionRecord): Promise<void> {
  record.session.status = 'stopped';
  record.session.statusDetail = null;
  stopPreviewProcess(record);
  sessions.delete(record.session.id);
  await fs.promises.rm(record.workspaceDir, { recursive: true, force: true }).catch((err: Error) => {
    console.warn(`[code-lab] failed to remove workspace ${record.workspaceDir}:`, err.message);
  });
}

function getOwnedRecord(sessionId: string, userId: string): CodeLabSessionRecord {
  const record = sessions.get(sessionId);
  if (!record || record.userId !== userId) {
    throw new CodeLabError('Code Lab session not found. It may have expired or run on another server instance.', 404);
  }
  touch(record);
  return record;
}

export function startCodeLabSession(userId: string, request: StartCodeLabSessionRequest): CodeLabSession {
  for (const existing of sessions.values()) {
    if (existing.userId === userId) void stopRecord(existing);
  }
  const active = [...sessions.values()].filter((record) => !isStopped(record)).length;
  if (active >= MAX_ACTIVE_SESSIONS) {
    throw new CodeLabError('Code Lab is at capacity. Try again in a few minutes.', 429);
  }

  ensureBackgroundTasks();
  const id = randomUUID();
  const now = Date.now();
  const record: CodeLabSessionRecord = {
    session: {
      id,
      project: request.project,
      repo: '',
      baseBranch: '',
      branchName: `code-lab/${id.slice(0, 8)}`,
      status: 'preparing',
      statusDetail: 'Resolving the project repository',
      preview: null,
      previewUrl: null,
      chatThreadId: null,
      branchPushed: false,
      createdAt: new Date(now).toISOString(),
      lastActivityAt: new Date(now).toISOString(),
    },
    userId,
    token: randomBytes(24).toString('base64url'),
    provider: 'ado',
    workspaceDir: path.join(WORKSPACE_ROOT, id),
    appDir: null,
    previewProcess: null,
    previewPort: null,
    lastActivityMs: now,
    logs: [],
  };
  sessions.set(id, record);
  void runSetup(record, request.model);
  return toPublic(record);
}

export function getActiveCodeLabSession(userId: string, project: string): CodeLabSession | null {
  for (const record of sessions.values()) {
    if (record.userId === userId && record.session.project === project && !isStopped(record)) {
      touch(record);
      return toPublic(record);
    }
  }
  return null;
}

export function getCodeLabSession(sessionId: string, userId: string): CodeLabSession {
  return toPublic(getOwnedRecord(sessionId, userId));
}

export async function stopCodeLabSession(sessionId: string, userId: string): Promise<void> {
  await stopRecord(getOwnedRecord(sessionId, userId));
}

export async function restartCodeLabPreview(sessionId: string, userId: string): Promise<CodeLabSession> {
  const record = getOwnedRecord(sessionId, userId);
  if (record.session.status === 'preparing' || record.session.status === 'failed') {
    throw new CodeLabError('The session is not ready for a preview restart.', 409);
  }
  stopPreviewProcess(record);
  record.session.preview = detectPreview(record.workspaceDir);
  void startPreview(record).catch((err: Error) => {
    setStatus(record, 'preview_unavailable', `Preview restart failed: ${err.message}`);
  });
  return toPublic(record);
}

export function getCodeLabLogs(sessionId: string, userId: string): CodeLabLogs {
  return { lines: [...getOwnedRecord(sessionId, userId).logs] };
}

function requireWorkspace(record: CodeLabSessionRecord): void {
  if (!fs.existsSync(path.join(record.workspaceDir, '.git'))) {
    throw new CodeLabError('The workspace is still being prepared.', 409);
  }
}

export async function getCodeLabDiff(sessionId: string, userId: string): Promise<CodeLabDiff> {
  const record = getOwnedRecord(sessionId, userId);
  requireWorkspace(record);
  const { diffText, changedFiles } = await computeDiff(record.workspaceDir);
  return { diffText, changedFiles, branch: record.session.branchName };
}

export async function pushCodeLabBranch(sessionId: string, userId: string): Promise<CodeLabPushResult> {
  const record = getOwnedRecord(sessionId, userId);
  requireWorkspace(record);
  const { changedFiles } = await computeDiff(record.workspaceDir);
  if (changedFiles.length === 0 && !record.session.branchPushed) {
    throw new CodeLabError('There are no changes to push yet.', 409);
  }
  const { session } = record;
  const remote = resolveGitRemote(record.provider, session.project, session.repo);
  await pushBranch(record.workspaceDir, session.branchName, remote);
  session.branchPushed = true;
  return { branch: session.branchName, changedFiles };
}

function previewTokenMatches(record: CodeLabSessionRecord, token: string): boolean {
  const expected = Buffer.from(record.token);
  const actual = Buffer.from(token);
  return expected.length === actual.length && timingSafeEqual(expected, actual);
}

function applyPreviewHeaders(res: Response): void {
  for (const [name, value] of Object.entries(PREVIEW_RESPONSE_HEADERS)) res.setHeader(name, value);
  res.removeHeader('Access-Control-Allow-Credentials');
}

function serveStaticPreview(record: CodeLabSessionRecord, relativePath: string, res: Response): void {
  const root = record.appDir;
  if (!root) {
    res.status(503).type('text/plain').send('Preview is not ready.');
    return;
  }
  const decoded = decodeURIComponent(relativePath || '');
  const target = decoded === '' || decoded.endsWith('/') ? `${decoded}index.html` : decoded;
  res.sendFile(target, { root, dotfiles: 'deny' }, (err) => {
    if (err && !res.headersSent) res.status(404).type('text/plain').send('Not found');
  });
}

function proxyToVite(record: CodeLabSessionRecord, req: Request, res: Response): void {
  const port = record.previewPort;
  if (!port || !record.session.previewUrl) {
    res.status(503).type('text/plain').send('The preview is starting. Reload in a moment.');
    return;
  }
  const headers: http.OutgoingHttpHeaders = { host: `127.0.0.1:${port}` };
  for (const name of FORWARDED_REQUEST_HEADERS) {
    const value = req.headers[name];
    if (value !== undefined) headers[name] = value;
  }
  const upstream = http.request(
    { host: '127.0.0.1', port, method: req.method, path: req.originalUrl, headers },
    (upstreamRes) => {
      const isHtml = String(upstreamRes.headers['content-type'] ?? '').includes('text/html');
      res.status(upstreamRes.statusCode ?? 502);
      for (const [name, value] of Object.entries(upstreamRes.headers)) {
        if (value === undefined || DROPPED_RESPONSE_HEADERS.has(name.toLowerCase())) continue;
        if (isHtml && name.toLowerCase() === 'content-length') continue;
        res.setHeader(name, value);
      }
      applyPreviewHeaders(res);
      if (!isHtml || req.method === 'HEAD') {
        upstreamRes.pipe(res);
        return;
      }
      const chunks: Buffer[] = [];
      upstreamRes.on('data', (chunk: Buffer) => chunks.push(chunk));
      upstreamRes.on('end', () => {
        res.send(injectRouteReset(Buffer.concat(chunks).toString('utf-8'), previewBasePath(record)));
      });
    },
  );
  upstream.on('error', (err) => {
    if (!res.headersSent) res.status(502).type('text/plain').send(`Preview server unavailable: ${err.message}`);
    else res.end();
  });
  req.on('close', () => upstream.destroy());
  upstream.end();
}

/**
 * Serves `/api/code-lab/preview/:sessionId/:token/*` without an Apex session.
 * The unguessable per-session token in the path is the credential.
 */
export function handleCodeLabPreviewRequest(
  req: Request,
  res: Response,
  sessionId: string,
  token: string,
  relativePath: string,
): void {
  const record = sessions.get(sessionId);
  if (!record || !previewTokenMatches(record, token)) {
    res.status(404).type('text/plain').send('Preview not found');
    return;
  }
  if (req.method !== 'GET' && req.method !== 'HEAD') {
    res.status(405).setHeader('Allow', 'GET, HEAD').end();
    return;
  }
  touch(record);
  applyPreviewHeaders(res);
  if (record.session.preview?.kind === 'static') {
    serveStaticPreview(record, relativePath, res);
    return;
  }
  proxyToVite(record, req, res);
}
